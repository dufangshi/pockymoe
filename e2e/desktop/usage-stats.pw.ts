import { expect, test } from '@playwright/test';
import { seed } from './fixtures';
const evidence = process.env.DESKTOP_EVIDENCE_DIR ?? '.scratch/usage-stats';
for (const pack of ['classic', 'plum-pocket', 'terminal']) for (const dark of [false, true]) for (const width of [1440, 390]) {
  test(`usage statistics ${pack} ${dark ? 'dark' : 'light'} ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1100 });
    await seed(page, pack, dark, false, false, true, true);
    await expect(page.locator('.pd-device-card')).toHaveCount(12);
    const captions = page.locator('.pd-chart-excluded');
    await expect(captions).toHaveCount(2);
    await expect(captions.first()).toContainText('1 台设备版本较旧，未计入');
    await expect(page.getByRole('group', { name: '今日每小时轮数，按设备堆叠', exact: true })).toBeVisible();
    await expect(page.getByRole('group', { name: '今日每小时 tokens', exact: true }).locator('[data-chart-bar]')).toHaveCount(24);
    await expect(page.locator('.pd-longest')).toHaveCount(0);
    const table = page.locator('.pd-account-models .pd-usage-table');
    await expect(table.locator('tfoot td').first()).toHaveText('218');
    await expect(table.getByRole('rowheader', { name: 'grok-4.7', exact: true })).toHaveCount(1);
    await expect(table.getByRole('rowheader', { name: '系统生成', exact: true })).toBeVisible();
    await expect(table).not.toContainText('remote-codex');
    await page.locator('.pd-account-models').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${evidence}/${pack}-${dark ? 'dark' : 'light'}-${width}-account.png` });
    const row = page.locator('.pd-usage-device-row').filter({ hasText: 'MacBook Pro' });
    await row.scrollIntoViewIfNeeded();
    const before = (await row.boundingBox())!.y;
    await row.locator('b').click();
    await expect(row).toHaveAttribute('aria-expanded', 'true');
    expect(Math.abs((await row.boundingBox())!.y - before)).toBeLessThanOrEqual(1);
    const details = row.locator('..').locator('.pd-device-details');
    await expect(details.getByRole('heading', { name: '模型', exact: true })).toHaveCount(0);
    await expect(details.getByRole('columnheader', { name: '模型', exact: true })).toHaveCount(1);
    await expect(details.getByRole('heading', { name: '工作区', exact: true })).toBeVisible();
    await expect(details.getByRole('rowheader', { name: 'grok-4.7', exact: true })).toHaveCount(1);
    expect(await details.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    const rightEdges = await details.locator('.pd-device-models tbody td:last-child .pd-usage-number > span:first-child').evaluateAll(elements => elements.map(el => el.getBoundingClientRect().right));
    expect(Math.max(...rightEdges) - Math.min(...rightEdges)).toBeLessThanOrEqual(1);
    await details.screenshot({ path: `${evidence}/${pack}-${dark ? 'dark' : 'light'}-${width}-models.png` });
    const expandedTop = (await row.boundingBox())!.y;
    await row.click();
    await expect(row).toHaveAttribute('aria-expanded', 'false');
    expect(Math.abs((await row.boundingBox())!.y - expandedTop)).toBeLessThanOrEqual(1);
    await page.getByRole('button', { name: '按费用', exact: true }).click();
    await expect(captions).toHaveCount(2);
    await expect(page.getByRole('group', { name: '今日每小时估算费用', exact: true }).locator('[data-chart-bar]')).toHaveCount(24);
    await page.locator('.pd-statistics').scrollIntoViewIfNeeded();
    await page.locator('.pd-statistics').screenshot({ path: `${evidence}/${pack}-${dark ? 'dark' : 'light'}-${width}-charts.png` });
    await page.getByRole('button', { name: '7 天', exact: true }).click();
    await expect(table.locator('tfoot td').first()).toHaveText('2436');
    await expect(page.locator('.pd-legend span')).toHaveCount(12);
    const colors = await page.locator('.pd-legend i').evaluateAll(elements => elements.map(el => getComputedStyle(el).backgroundColor));
    expect(new Set(colors).size).toBe(12);
    await page.locator('.pd-statistics').scrollIntoViewIfNeeded();
    await page.locator('.pd-statistics').screenshot({ path: `${evidence}/${pack}-${dark ? 'dark' : 'light'}-${width}-palette.png` });
    expect(await page.locator('.pd-page').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  });
}

test('category colours persist across range, metric and device filters', async ({ page }) => {
  await seed(page, 'classic', false, false, false, true, true);
  const row = page.locator('.pd-usage-device-row').filter({ hasText: 'MacBook Pro' });
  const model = page.locator('.pd-account-models .pd-usage-table').getByRole('rowheader', { name: 'gpt-6.1-sol', exact: true });
  const deviceColor = await row.locator('.pd-horizontal-track i').evaluate(el => getComputedStyle(el).backgroundColor);
  const modelColor = await model.locator('i').evaluate(el => getComputedStyle(el).backgroundColor);
  await page.getByRole('button', { name: '7 天', exact: true }).click();
  await page.getByRole('button', { name: '按费用', exact: true }).click();
  await expect.poll(() => row.locator('.pd-horizontal-track i').evaluate(el => getComputedStyle(el).backgroundColor)).toBe(deviceColor);
  await expect.poll(() => model.locator('i').evaluate(el => getComputedStyle(el).backgroundColor)).toBe(modelColor);
  await page.getByRole('combobox', { name: '统计设备', exact: true }).click();
  await page.getByRole('option', { name: 'MacBook Pro', exact: true }).click();
  await expect(page.locator('.pd-device-card')).toHaveCount(1);
  await expect.poll(() => row.locator('.pd-horizontal-track i').evaluate(el => getComputedStyle(el).backgroundColor)).toBe(deviceColor);
  await expect.poll(() => model.locator('i').evaluate(el => getComputedStyle(el).backgroundColor)).toBe(modelColor);
});
