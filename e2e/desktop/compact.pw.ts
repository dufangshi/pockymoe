import { expect, test } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { seed } from './fixtures';
const evidence = process.env.DESKTOP_EVIDENCE_DIR ?? 'test-results/desktop/compact';
mkdirSync(evidence, { recursive: true });
for (const pack of ['classic', 'plum-pocket', 'terminal']) for (const dark of [false, true]) for (const width of [1440, 900, 390]) {
  test(`compact real-account shape ${pack} ${dark ? 'dark' : 'light'} ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1100 });
    await seed(page, pack, dark, false, true);
    const name = `${pack}-${dark ? 'dark' : 'light'}-${width}`;
    await expect(page.locator('.pd-device-card')).toHaveCount(11);
    await expect.poll(async () => (await page.locator('.pd-page').boundingBox())!.width).toBeGreaterThanOrEqual(Math.min(width - 20, 260));
    expect((await page.locator('.pd-page-header').boundingBox())!.height).toBeLessThanOrEqual(40);
    expect((await page.locator('.pd-device-card').first().boundingBox())!.height).toBeLessThanOrEqual(100);
    await expect(page.locator('.pd-page select')).toHaveCount(0);
    await expect(page.locator('.pd-page')).not.toContainText('≈ —');
    await expect(page.getByRole('article', { name: 'wsl', exact: true })).toContainText('21');
    await expect(page.getByRole('article', { name: 'Empty device', exact: true }).locator('.pd-counts')).toContainText('0');
    await expect(page.getByRole('article', { name: 'wsl', exact: true }).getByRole('button', { name: '更新以获取完整统计', exact: true })).toBeVisible();
    await expect(page.locator('.pd-usage-table tbody tr').first()).toContainText('GPT-6.1');
    const usageWidth = (await page.locator('.pd-account-usage').boundingBox())!.width;
    expect((await page.locator('.pd-account-models').boundingBox())!.width).toBeGreaterThanOrEqual(usageWidth - 1);
    await page.screenshot({ path: `${evidence}/${name}-overview.png`, fullPage: true });
    const picker = page.getByRole('combobox', { name: '统计设备', exact: true });
    await picker.click();
    await page.keyboard.press('End');
    await expect(page.getByRole('option').last()).toBeFocused();
    await page.screenshot({ path: `${evidence}/${name}-device-filter.png` });
    await page.keyboard.press('Escape');
    await expect(picker).toBeFocused();
    const donut = page.locator('.pd-donut circle[tabindex]').first();
    await donut.focus(); await expect(page.locator('.pd-donut-tip')).toContainText('GPT-6.1');
    await page.locator('.pd-account-usage').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${evidence}/${name}-tokens.png` });
    await page.getByRole('button', { name: '按费用', exact: true }).click();
    await expect(page.locator('.pd-usage-table tbody tr').first()).toContainText('Claude Sonnet 4.6');
    await page.locator('.pd-usage-device-row').first().click();
    await expect(page.locator('.pd-workspace-usage a').first()).toBeVisible();
    await expect(page.locator('.pd-usage-device-row').first()).toContainText('Windows Studio');
    await page.screenshot({ path: `${evidence}/${name}-cost-expanded.png` });
    await page.getByRole('button', { name: '按 Token', exact: true }).click();
    await page.getByRole('button', { name: '全部', exact: true }).click();
    await expect(page.locator('.pd-page')).not.toContainText('≈ —');
    const old = page.locator('.pd-usage-device-row').filter({ hasText: 'wsl' });
    await expect(old).not.toContainText('—');
    await page.locator('.pd-longest summary').click();
    await expect(page.locator('.pd-longest a')).toHaveCount(5);
    await page.locator('.pd-statistics').scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${evidence}/${name}-statistics.png` });
    expect(await page.locator('.pd-page').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    writeFileSync(`${evidence}/${name}-geometry.json`, JSON.stringify(await page.locator('.pd-device-card').evaluateAll(cards => cards.filter(card => card.scrollWidth > card.clientWidth).map(card => ({ name: card.getAttribute('aria-label'), width: card.clientWidth, scroll: card.scrollWidth, children: [...card.querySelectorAll('*')].filter(el => el.getBoundingClientRect().right > card.getBoundingClientRect().right).map(el => ({ className: el.className, right: el.getBoundingClientRect().right, text: el.textContent?.slice(0,80) })) }))), null, 2));
    expect(await page.locator('.pd-device-card').evaluateAll(cards => cards.every(el => el.scrollWidth <= el.clientWidth + 1))).toBe(true);
  });
}

test('custom device/origin filters, legacy updater and stable refresh', async ({ page }) => {
  await seed(page, 'classic', false, false, true);
  const old = page.getByRole('article', { name: 'wsl', exact: true });
  await old.getByRole('button', { name: '更新以获取完整统计', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('0.12.73'); await page.keyboard.press('Escape');
  await page.getByRole('combobox', { name: '统计设备', exact: true }).click();
  await page.getByRole('option', { name: 'MacBook Pro', exact: true }).click();
  await expect(page.locator('.pd-device-card')).toHaveCount(1);
  await page.locator('.pd-page').evaluate(el => el.setAttribute('data-preserved', 'yes'));
  await page.getByRole('button', { name: '刷新', exact: true }).click();
  await expect(page.locator('.pd-page')).toHaveAttribute('data-preserved', 'yes');
  await page.getByRole('combobox', { name: '轮次来源', exact: true }).click();
  await page.getByRole('option', { name: '访客', exact: true }).click();
  await expect(page).toHaveURL(/origin=guest/);
  await expect(page.locator('.pd-usage-table tbody tr')).toHaveCount(2);
  await page.screenshot({ path: `${evidence}/origin-guest.png` });
});
