import { test, expect } from '@playwright/test';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';

const base = `http://127.0.0.1:${process.env.E2E_API_PORT ?? 8787}`;
test('language switch synchronizes host and shared workbench, preserves draft, files and refresh preference', async ({ page, request }) => {
  const absPath = path.resolve(process.env.E2E_WORKSPACE_ROOT!, `locale-${randomUUID()}`);
  await mkdir(absPath, { recursive: true });
  await writeFile(path.join(absPath, 'notes.txt'), 'User file content in English');
  const workspaceResponse = await request.post(`${base}/api/workspaces`, { data: { absPath, label: 'English workspace name' } });
  expect(workspaceResponse.ok()).toBeTruthy();
  const workspace = await workspaceResponse.json();
  const startedResponse = await request.post(`${base}/api/threads/start`, { data: { workspaceId: workspace.id, title: 'English user title', provider: 'acp', agentId: 'grok', model: 'ios-e2e-stream', approvalMode: 'yolo' } });
  expect(startedResponse.ok()).toBeTruthy();
  const started = await startedResponse.json();
  const id = started.id ?? started.thread.id;
  await page.goto(`/threads/${id}`);
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  const composer = page.getByRole('textbox', { name: 'Prompt', exact: true });
  await composer.fill('Keep my English draft');
  await page.getByRole('button', { name: 'Open settings', exact: true }).click();
  await page.getByRole('tab', { name: 'Preferences', exact: true }).click();
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('zh-CN');
  await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN');
  await expect(page.getByRole('tab', { name: '偏好设置', exact: true })).toBeVisible();
  await expect(page.getByRole('group', { name: '外观', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('textbox', { name: '提示词', exact: true })).toHaveText('Keep my English draft');
  await expect(page.getByText('English user title', { exact: true }).first()).toBeVisible();
  await expect(page.getByRole('button', { name: '切换文件浏览器', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '切换文件浏览器', exact: true }).click();
  await expect(page.getByRole('complementary', { name: '文件浏览器', exact: true })).toBeVisible();
  await expect(page.getByRole('treeitem', { name: 'notes.txt', exact: true })).toBeVisible();
  await page.getByRole('treeitem', { name: 'notes.txt', exact: true }).focus();
  await page.getByRole('treeitem', { name: 'notes.txt', exact: true }).press('Enter');
  await expect(page.getByRole('button', { name: '编辑文件', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '编辑文件', exact: true }).click();
  await expect(page.getByRole('button', { name: '保存文件', exact: true })).toBeVisible();
  const editor = page.getByRole('textbox', { name: '工作区编辑器：notes.txt', exact: true });
  await editor.focus();
  await editor.press('ControlOrMeta+A');
  await page.keyboard.insertText('Edited user content in English');
  await page.getByRole('button', { name: '保存文件', exact: true }).click();
  await expect.poll(() => readFile(path.join(absPath, 'notes.txt'), 'utf8')).toBe('Edited user content in English');
  page.on('dialog', dialog => dialog.accept());
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN');
  await expect(page.getByText('English user title', { exact: true }).first()).toBeVisible();
  // Exercise the combined search + i18n build, including cached result labels.
  await page.getByRole('button', { name: '搜索对话', exact: true }).click();
  await page.getByRole('combobox', { name: '搜索范围', exact: true }).selectOption('workspace');
  await page.getByRole('combobox', { name: '搜索消息', exact: true }).fill('English user title');
  const localizedResults = page.getByRole('listbox', { name: '匹配消息', exact: true });
  await expect(localizedResults.getByRole('option')).toHaveCount(1);
  await expect(localizedResults).toContainText('标题');
  await page.getByRole('button', { name: '关闭搜索', exact: true }).click();
  await page.getByRole('button', { name: '打开设置', exact: true }).click();
  await page.getByRole('tab', { name: '偏好设置', exact: true }).click();
  await expect(page.getByRole('combobox', { name: '语言', exact: true })).toHaveValue('zh-CN');
  await page.getByRole('combobox', { name: '语言', exact: true }).selectOption('en');
  await expect(page.getByRole('tab', { name: 'Preferences', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Search conversation', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Search scope', exact: true })).toHaveValue('workspace');
  await expect(page.getByRole('listbox', { name: 'Matching messages', exact: true })).toContainText('Title');
  await page.getByRole('button', { name: 'Close search', exact: true }).click();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  await expect(page.getByRole('button', { name: 'Toggle Explorer', exact: true })).toBeVisible();
});

test('browser locale aliases initialize Chinese and unsupported saved locales fall back to English', async ({ browser }) => {
  const context = await browser.newContext({ locale: 'zh-SG', viewport: { width: 390, height: 844 } });
  try {
    const page = await context.newPage();
    await page.goto('/workspaces');
    await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN');
    await expect(page.getByRole('heading', { name: '工作区', exact: true }).first()).toBeVisible();
    await page.getByRole('button', { name: '打开导航', exact: true }).click();
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('tab', { name: '偏好设置', exact: true }).click();
    await expect(page.getByRole('combobox', { name: '语言', exact: true })).toBeVisible();
    await page.getByRole('combobox', { name: '语言', exact: true }).selectOption('en');
    await page.keyboard.press('Escape');
    await page.reload();
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    await page.evaluate(() => localStorage.setItem('remote-codex.locale', 'fr-FR'));
    await page.reload();
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    await expect(page.getByRole('heading', { name: 'Workspaces', exact: true }).first()).toBeVisible();
  } finally { await context.close(); }
});
