"""Derive Rust wire structs from Codex's own generated request schemas."""
import json, pathlib, re, sys
root = pathlib.Path(sys.argv[1])
output = ['// Generated by scripts/generate-codex-schema.sh; do not edit.', 'use serde::Serialize;']
for name in ['ThreadRevertParams', 'TurnInterruptParams', 'ThreadCompactStartParams', 'ThreadGoalGetParams', 'ThreadGoalSetParams']:
    schema = json.loads((root / 'v2' / (name + '.json')).read_text())
    output += ['#[derive(Debug, Serialize)]', '#[serde(rename_all = "camelCase")]', 'pub struct ' + name + ' {']
    for key, prop in schema['properties'].items():
        kind = prop.get('type', '')
        if isinstance(kind, list): kind = next((k for k in kind if k != 'null'), '')
        ty = {'string':'String', 'integer':'i64', 'boolean':'bool'}.get(kind, 'serde_json::Value')
        if key not in schema.get('required', []): ty = 'Option<' + ty + '>'
        snake = re.sub(r'(?<!^)(?=[A-Z])', '_', key).lower()
        output.append('    pub ' + snake + ': ' + ty + ',')
    output.append('}')
pathlib.Path('crates/runtime/src/native/codex/wire.rs').write_text('\n'.join(output) + '\n')
