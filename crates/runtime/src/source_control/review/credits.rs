//! "Remove agent credits when merging": drop the co-author and "Generated with"
//! lines coding agents add, keep every human co-author. Only the e-mail decides
//! whether a co-author is an agent, never the name, so a person called "Claude"
//! keeps their credit. Code blocks are never touched.

/// Addresses agents sign with. `noreply@github.com` is ambiguous (GitHub's
/// generic privacy address), so it counts only with Copilot's name.
const AGENT_EMAILS: &[&str] = &[
    "noreply@anthropic.com",
    "claude@anthropic.com",
    "noreply@openai.com",
    "codex@openai.com",
    "cursoragent@cursor.com",
    "copilot@github.com",
];
const AGENT_NAMES: &[&str] = &[
    "claude code",
    "claude",
    "codex",
    "cursor",
    "github copilot",
    "copilot",
    "opencode",
    "grok",
    "antigravity",
    "pockymoe",
];
const AGENT_SITES: &[&str] = &[
    "claude.ai",
    "claude.com",
    "www.anthropic.com",
    "chatgpt.com",
    "openai.com",
    "cursor.com",
    "github.com",
    "opencode.ai",
    "x.ai",
    "antigravity.google",
];

/// `[text](https://agent-site/...)` → `text`, so "Generated with [Claude Code](…)" matches.
fn strip_agent_links(line: &str) -> String {
    let mut out = String::new();
    let mut rest = line;
    while let Some(open) = rest.find('[') {
        let after = &rest[open + 1..];
        let Some(close) = after.find("](") else { break };
        let text = &after[..close];
        let target = &after[close + 2..];
        let Some(end) = target.find(')') else { break };
        let url = &target[..end];
        let site = url
            .strip_prefix("https://")
            .map(|u| u.split(['/', '?', '#']).next().unwrap_or(""));
        if !text.contains(['[', ']']) && site.is_some_and(|s| AGENT_SITES.contains(&s)) {
            out.push_str(&rest[..open]);
            out.push_str(text);
        } else {
            out.push_str(&rest[..open + 1 + close + 2 + end + 1]);
        }
        rest = &target[end + 1..];
    }
    out.push_str(rest);
    out
}

fn generated_by_agent(line: &str) -> bool {
    let line = strip_agent_links(line);
    let line = line.trim_start_matches('🤖').trim();
    let lower = line.to_lowercase();
    let lower = lower.trim_end_matches(['.', '!']);
    for verb in ["generated with ", "generated by "] {
        if let Some(name) = lower.strip_prefix(verb) {
            return AGENT_NAMES.contains(&name.trim());
        }
    }
    false
}

fn agent_co_author(line: &str) -> bool {
    let lower = line.to_lowercase();
    let Some(value) = lower.strip_prefix("co-authored-by:") else {
        return false;
    };
    let (Some(start), Some(end)) = (value.rfind('<'), value.rfind('>')) else {
        return false;
    };
    if end < start {
        return false;
    }
    let email = value[start + 1..end].trim();
    let name = value[..start].trim();
    AGENT_EMAILS.contains(&email)
        || (email == "noreply@github.com" && matches!(name, "copilot" | "github copilot"))
}

/// The message without agent credits. Unchanged input is returned as is.
pub fn remove_agent_credits(message: &str) -> String {
    let crlf = message.contains("\r\n");
    let mut kept: Vec<&str> = Vec::new();
    let mut fence: Option<&str> = None;
    let mut removed = false;
    for raw in message.split('\n') {
        let line = raw.strip_suffix('\r').unwrap_or(raw);
        let trimmed = line.trim();
        if let Some(marker) = fence {
            if trimmed.starts_with(marker) {
                fence = None;
            }
            kept.push(line);
            continue;
        }
        if trimmed.starts_with("```") || trimmed.starts_with("~~~") {
            fence = Some(&trimmed[..3]);
            kept.push(line);
            continue;
        }
        if line.starts_with("    ") || line.starts_with('\t') {
            kept.push(line);
            continue;
        }
        let bare = trimmed
            .strip_prefix("- ")
            .or_else(|| trimmed.strip_prefix("* "))
            .unwrap_or(trimmed);
        if agent_co_author(bare) || generated_by_agent(bare) {
            removed = true;
            continue;
        }
        kept.push(line);
    }
    if !removed {
        return message.into();
    }
    while kept.last().is_some_and(|l| l.trim().is_empty()) {
        kept.pop();
    }
    // Two blank lines left where a block of credits was become one.
    let mut out: Vec<&str> = Vec::new();
    for line in kept {
        if line.trim().is_empty() && out.last().is_some_and(|l| l.trim().is_empty()) {
            continue;
        }
        out.push(line);
    }
    out.join(if crlf { "\r\n" } else { "\n" })
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn removes_agent_credits_and_keeps_people_and_code() {
        let message = "Fix the parser (#12)\n\n* Handle empty input\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\nCo-authored-by: Ada Lovelace <ada@example.com>\nCo-authored-by: Claude Shannon <claude@example.org>\nCo-authored-by: Codex <codex@openai.com>\n- Co-authored-by: Copilot <noreply@github.com>\nCo-authored-by: Jane <noreply@github.com>\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n";
        let cleaned = remove_agent_credits(message);
        assert_eq!(
            cleaned,
            "Fix the parser (#12)\n\n* Handle empty input\n\nCo-authored-by: Ada Lovelace <ada@example.com>\nCo-authored-by: Claude Shannon <claude@example.org>\nCo-authored-by: Jane <noreply@github.com>"
        );
        let code = "Docs\n\n```\nCo-Authored-By: Claude <noreply@anthropic.com>\n```\n    Generated with Codex";
        assert_eq!(remove_agent_credits(code), code);
        assert_eq!(remove_agent_credits("Plain\n"), "Plain\n");
        assert_eq!(
            remove_agent_credits("A\r\n\r\nGenerated by Codex.\r\n"),
            "A"
        );
        // A link to an unrelated site is not an agent credit.
        let other = "Generated with [Claude Code](https://example.com/x)";
        assert_eq!(remove_agent_credits(other), other);
    }
}
